// JVMAnalyzer.swift
// Core/Analyzers
//
// Classifies JVM / Java sprawl: old JDK installations, Kotlin/Native prebuilts,
// SBT ivy/coursier cache, Android build cache, JetBrains IDE caches.

import Foundation

public struct JVMAnalyzer: StorageAnalyzer {

    public let id = "com.reclaim.jvm"
    public let displayName = "JVM / Java"

    private static let markers: [String] = [
        "/library/java/javavirtualmachines",
        "/library/java/jdk",
        "/.konan",
        "/.ivy2/cache", "/.ivy2/local",
        "/.sbt",
        "/.cache/coursier", "/.coursier",
        "/.android/build-cache",
        "/library/application support/jetbrains",
    ]

    public func canAnalyze(_ item: StorageItem) -> Bool {
        let lower = item.path.lowercased()
        return Self.markers.contains { lower.contains($0) }
    }

    public func analyze(item: StorageItem, context: AnalysisContext) async throws -> AnalysisResult {
        let lower = item.path.lowercased()

        var enriched = item
        enriched.category = .jvm
        enriched.analyzerID = id

        let isCandidate: Bool
        let note: String

        switch true {
        case lower.contains("/.ivy2/cache") || lower.contains("/.cache/coursier"):
            enriched.risk = .safe
            enriched.recoverability = .redownloadable
            enriched.whatIsThis = "ivy2 / Coursier dependency cache — re-downloaded automatically on next build"
            isCandidate = true
            note = "ivy2/Coursier cache"

        case lower.contains("/.konan"):
            enriched.risk = .safe
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "Kotlin/Native prebuilt libraries — regenerated by Kotlin compiler"
            isCandidate = true
            note = "Kotlin/Native prebuilts"

        case lower.contains("/.sbt"):
            enriched.risk = .low
            enriched.recoverability = .redownloadable
            enriched.whatIsThis = "SBT global plugins and settings — re-downloaded by sbt"
            isCandidate = true
            note = "SBT global"

        case lower.contains("/library/java/javavirtualmachines"):
            enriched.risk = .low
            enriched.recoverability = .redownloadable
            enriched.whatIsThis = "Old JDK installation — verify it's not your active Java before removing"
            enriched.removalConsequence = "If this is the active JDK, Java projects will not compile."
            isCandidate = true
            note = "JDK installation"

        case lower.contains("/.android/build-cache"):
            enriched.risk = .safe
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "Android build cache — rebuilt automatically by Gradle"
            isCandidate = true
            note = "Android build cache"

        case lower.contains("/library/application support/jetbrains"):
            enriched.risk = .medium
            enriched.recoverability = .userData
            enriched.whatIsThis = "JetBrains IDE settings / caches — contains IDE preferences and project indexes"
            isCandidate = false
            note = "JetBrains IDE data"

        default:
            enriched.risk = .low
            enriched.recoverability = .redownloadable
            enriched.whatIsThis = "JVM / Java build artifact"
            isCandidate = true
            note = "JVM artifact"
        }

        return AnalysisResult(
            item: enriched,
            evidence: [Evidence(kind: .note, description: note)],
            isCleanupCandidate: isCandidate,
            rejectionReason: isCandidate ? nil : "IDE user data — not auto-cleaned"
        )
    }
}
