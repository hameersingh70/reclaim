// PythonEnvAnalyzer.swift
// Core/Analyzers
//
// Classifies Python environment sprawl: pyenv versions, conda/mamba envs,
// pip download cache, virtualenv dirs, __pycache__, pytest cache, tox envs.

import Foundation

public struct PythonEnvAnalyzer: StorageAnalyzer {

    public let id = "com.reclaim.pythonenv"
    public let displayName = "Python Environments"

    private static let markers: [String] = [
        "/.pyenv/versions", "/.pyenv/shims",
        "/miniconda3/pkgs", "/miniconda3/envs",
        "/anaconda3/pkgs", "/anaconda3/envs",
        "/.conda/pkgs", "/.conda/envs",
        "/miniforge3/pkgs", "/miniforge3/envs",
        "/mambaforge/pkgs", "/mambaforge/envs",
        "/.cache/pip", "/.pip/cache", "/library/caches/pip",
        "/.cache/uv", "/uv/cache",
        "/.cache/pypoetry", "/pypoetry",
        "/.tox/",
        "/site-packages",
        "/__pycache__",
        "/.pytest_cache",
        "/dist-info", "/.eggs",
        "/venv/lib/python", "/.venv/lib/python",
        "/env/lib/python", "/.env/lib/python",
    ]

    public func canAnalyze(_ item: StorageItem) -> Bool {
        let lower = item.path.lowercased()
        return Self.markers.contains { lower.contains($0) }
    }

    public func analyze(item: StorageItem, context: AnalysisContext) async throws -> AnalysisResult {
        let lower = item.path.lowercased()

        var enriched = item
        enriched.category = .pythonEnv
        enriched.analyzerID = id

        let isCandidate: Bool
        let note: String

        switch true {
        case lower.contains("/.cache/pip") || lower.contains("/.pip/cache") || lower.contains("/library/caches/pip"):
            enriched.risk = .safe
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "pip download cache — re-downloaded automatically on next install"
            enriched.recoveryInstruction = "pip re-downloads packages when needed"
            isCandidate = true
            note = "pip cache"

        case lower.contains("/.cache/uv") || lower.contains("/uv/cache"):
            enriched.risk = .safe
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "Astral uv cache — wheel and source cache for Python package manager"
            enriched.recoveryInstruction = "uv re-downloads wheels when needed (or `uv cache clean`)"
            isCandidate = true
            note = "uv cache"

        case lower.contains("/pypoetry"):
            enriched.risk = .safe
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "Poetry cache — virtualenvs and artifacts cache for Poetry"
            enriched.recoveryInstruction = "Poetry re-downloads dependencies as needed"
            isCandidate = true
            note = "poetry cache"

        case lower.contains("/pkgs") && (lower.contains("conda") || lower.contains("miniforge") || lower.contains("mamba")):
            enriched.risk = .safe
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "conda package cache — re-downloaded by conda when needed"
            isCandidate = true
            note = "conda pkgs cache"

        case lower.contains("/__pycache__"):
            enriched.risk = .safe
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "Python bytecode cache — always regenerated by the Python interpreter"
            isCandidate = true
            note = "__pycache__"

        case lower.contains("/.pytest_cache"):
            enriched.risk = .safe
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "pytest cache directory — regenerated on next test run"
            isCandidate = true
            note = "pytest cache"

        case lower.contains("/.tox/"):
            enriched.risk = .low
            enriched.recoverability = .rebuildable
            enriched.whatIsThis = "tox test environment — recreatable with `tox`"
            enriched.recoveryInstruction = "Run: tox"
            isCandidate = true
            note = "tox env"

        case lower.contains("/.pyenv/versions"):
            enriched.risk = .low
            enriched.recoverability = .redownloadable
            enriched.whatIsThis = "pyenv Python version — re-installable with `pyenv install <version>`"
            enriched.recoveryInstruction = "Run: pyenv install <version>"
            isCandidate = true
            note = "pyenv Python version"

        case (lower.contains("conda") || lower.contains("miniforge") || lower.contains("mamba"))
            && lower.contains("/envs/"):
            enriched.risk = .low
            enriched.recoverability = .rebuildable
            enriched.whatIsThis = "conda environment — recreatable from environment.yml"
            enriched.recoveryInstruction = "Run: conda env create -f environment.yml"
            isCandidate = true
            note = "conda environment"

        case lower.contains("/venv/lib/python") || lower.contains("/.venv/lib/python")
            || lower.contains("/env/lib/python"):
            enriched.risk = .low
            enriched.recoverability = .rebuildable
            enriched.whatIsThis = "Python virtual environment — recreatable with `pip install -r requirements.txt`"
            enriched.recoveryInstruction = "Run: python -m venv .venv && pip install -r requirements.txt"
            isCandidate = true
            note = "Python venv"

        case lower.contains("/site-packages"):
            enriched.risk = .medium
            enriched.recoverability = .rebuildable
            enriched.whatIsThis = "Python site-packages directory — can be reinstalled, verify env first"
            isCandidate = true
            note = "site-packages"

        default:
            enriched.risk = .low
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "Python environment artifact"
            isCandidate = true
            note = "Python artifact"
        }

        return AnalysisResult(
            item: enriched,
            evidence: [Evidence(kind: .note, description: note)],
            isCleanupCandidate: isCandidate
        )
    }
}
