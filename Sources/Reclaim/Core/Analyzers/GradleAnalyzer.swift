// GradleAnalyzer.swift
// Analyzers/Gradle
//
// Detects and classifies Gradle caches, distributions, and logs per PRD §9.
// Does NOT blindly classify the entire .gradle directory as safe.

import Foundation

public struct GradleAnalyzer: StorageAnalyzer {
    public let id = "com.reclaim.analyzers.gradle"
    public let displayName = "Gradle Analyzer"

    public init() {}

    public func canAnalyze(_ item: StorageItem) -> Bool {
        let lower = item.path.lowercased()
        return lower.contains("/.gradle") || lower.hasSuffix("/.gradle")
    }

    public func analyze(item: StorageItem, context: AnalysisContext) async throws -> AnalysisResult {
        var enriched = item
        enriched.category = .gradle
        enriched.analyzerID = id

        let lower = item.path.lowercased()
        var evidence: [Evidence] = []
        var isCandidate = false
        var rejectionReason: String? = nil

        if lower.hasSuffix("/.gradle") || lower.hasSuffix("/.gradle/") {
            // Root .gradle directory
            enriched.risk = .high
            enriched.recoverability = .userData
            enriched.whatIsThis = "Gradle home directory"
            enriched.whyItExists = "Contains global configuration, properties, daemon state, and caches."
            enriched.removalConsequence = "Removes global Gradle configuration, daemon state, and caches."
            enriched.recoveryInstruction = "Recreated on next Gradle execution, but user properties may be lost."
            isCandidate = false
            rejectionReason = "Root .gradle directory should not be completely deleted."
            evidence.append(Evidence(kind: .note, description: "Protected root .gradle folder"))
        } else if lower.contains("/caches/modules-2") || lower.contains("/caches/build-cache") {
            enriched.risk = .low
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "Gradle dependency & build cache"
            enriched.whyItExists = "Stores downloaded library dependencies and incremental build outputs."
            enriched.removalConsequence = "The next build may take longer as dependencies are re-downloaded."
            enriched.recoveryInstruction = "Dependencies download automatically during the next build."
            isCandidate = true
            evidence.append(Evidence(kind: .pathMatch, description: "Matched Gradle dependency/build cache path"))
        } else if lower.contains("/wrapper/dists") {
            enriched.risk = .low
            enriched.recoverability = .redownloadable
            enriched.whatIsThis = "Gradle wrapper binary distributions"
            enriched.whyItExists = "Stores installed Gradle toolchains downloaded by gradlew."
            enriched.removalConsequence = "Next run of ./gradlew will re-download the Gradle distribution zip."
            enriched.recoveryInstruction = "Automatic upon running ./gradlew."
            isCandidate = true
            evidence.append(Evidence(kind: .pathMatch, description: "Matched Gradle wrapper distribution"))
        } else if lower.contains("/daemon") {
            enriched.risk = .safe
            enriched.recoverability = .regeneratable
            enriched.whatIsThis = "Gradle daemon runtime logs"
            enriched.whyItExists = "Logs and lock files generated by background Gradle build daemons."
            enriched.removalConsequence = "Deletes historical daemon logs. No impact on builds."
            enriched.recoveryInstruction = "Regenerated automatically when daemons start."
            isCandidate = true
            evidence.append(Evidence(kind: .pathMatch, description: "Matched Gradle daemon logs"))
        } else {
            // Other subdirectories in .gradle
            enriched.risk = .medium
            enriched.recoverability = .unknown
            enriched.whatIsThis = "Gradle cache or metadata"
            isCandidate = false
            rejectionReason = "Unknown Gradle subdirectory requires review."
        }

        return AnalysisResult(
            item: enriched,
            evidence: evidence,
            isCleanupCandidate: isCandidate,
            rejectionReason: rejectionReason
        )
    }
}
